from core.normalized_finding import NormalizedFinding


RULE_ID = "LINUX-SSH-001"


def detect_unexpected_authorized_keys(events, expected_key_ids):
    """
    Detect authorized SSH keys that are not present in the supplied baseline.

    expected_key_ids must contain SHA-256 identifiers generated by the parser.
    """

    if expected_key_ids is None:
        raise ValueError("An expected SSH key baseline is required")

    expected_key_ids = set(expected_key_ids)
    findings = []

    for event in events:
        if event.platform != "linux":
            continue

        if event.event_type != "ssh_authorized_key":
            continue

        key_id = event.metadata.get("key_id")

        if not key_id or key_id in expected_key_ids:
            continue

        if not event.evidence_reference:
            continue

        findings.append(
            NormalizedFinding(
                finding_id=f"{RULE_ID}-{len(findings) + 1:04d}",
                rule_id=RULE_ID,
                severity="medium",
                status="unverified",
                message="SSH authorized key is not present in the expected baseline",
                evidence_reference=event.evidence_reference,
                metadata={
                    "key_id": key_id,
                    "key_type": event.metadata.get("key_type"),
                    "comment": event.metadata.get("comment"),
                    "line_number": event.metadata.get("line_number")
                }
            )
        )

    return findings
